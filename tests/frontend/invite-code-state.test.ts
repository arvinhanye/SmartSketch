import { flushPromises } from '@vue/test-utils'
import { describe, expect, it } from 'vitest'
import type { Course } from '../../src/frontend/src/api/courses'
import type { InviteCodeResponse } from '../../src/frontend/src/api/inviteCode'
import { course, deferred, fakeInvite, invite, mountInvite, nextInvite, submitCode } from './invite-code-helpers'

describe('邀请码异步边界', () => {
  it('学生提交同步防重入，并禁用输入与按钮直到刷新结束', async () => {
    const pending = deferred<Course>()
    const refreshed = deferred<Course[]>()
    let lists = 0
    const h = await mountInvite({ inviteApi: fakeInvite({ join: () => pending.promise }), courses: { list: () => ++lists === 1 ? Promise.resolve([]) : refreshed.promise } })
    await h.wrapper.get('[data-test="course-join-code"]').setValue(invite.code)
    const form = h.wrapper.get('[data-test="course-join"]').element
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    await flushPromises()
    expect(h.api.join).toHaveBeenCalledTimes(1)
    expect(h.wrapper.get('[data-test="course-join-submit"]').attributes('disabled')).toBeDefined()
    expect(h.wrapper.get('[data-test="course-join-code"]').attributes('disabled')).toBeDefined()
    pending.resolve(course)
    await flushPromises()
    expect(h.wrapper.get('[data-test="course-join-submit"]').attributes('disabled')).toBeDefined()
    refreshed.resolve([course])
    await flushPromises()
    expect(h.wrapper.get('[data-test="course-join-submit"]').attributes('disabled')).toBeUndefined()
  })
  it.each(['resolve', 'reject'] as const)('换号取消入课并忽略旧请求%s', async (outcome) => {
    const pending = deferred<Course>()
    const h = await mountInvite({ inviteApi: fakeInvite({ join: () => pending.promise }) })
    await submitCode(h)
    const signal = h.api.join.mock.calls[0]![1]!.signal!
    h.signIn('session-two')
    await flushPromises()
    expect(signal.aborted).toBe(true)
    if (outcome === 'resolve') pending.resolve(course)
    else pending.reject(new Error('private old session'))
    await flushPromises()
    expect(h.wrapper.find('[data-test="course-join-success"]').exists()).toBe(false)
    expect(h.wrapper.find('[data-test="course-join-error"]').exists()).toBe(false)
    expect(h.wrapper.get<HTMLInputElement>('[data-test="course-join-code"]').element.value).toBe('')
    expect(h.wrapper.find('.is-new').exists()).toBe(false)
  })
  it('入课未完成时进入课程详情，取消旧请求且不高亮详情页的卡片', async () => {
    const pending = deferred<Course>()
    const h = await mountInvite({ inviteApi: fakeInvite({ join: () => pending.promise }), courses: { list: async () => [course] } })
    await submitCode(h)
    const signal = h.api.join.mock.calls[0]![1]!.signal!
    await h.router.push('/courses/joined')
    await flushPromises()
    expect(signal.aborted).toBe(true)
    pending.resolve(course)
    await flushPromises()
    expect(h.wrapper.find('[data-test="course-join"]').exists()).toBe(false)
    expect(h.wrapper.find('.is-new').exists()).toBe(false)
    expect(h.courses.list).toHaveBeenCalledTimes(1)
  })
  it('刷新列表期间离开列表页，迟到的入课完成不留下高亮或回执', async () => {
    const refreshed = deferred<Course[]>()
    let lists = 0
    const h = await mountInvite({ courses: { list: () => ++lists === 1 ? Promise.resolve([]) : refreshed.promise } })
    await submitCode(h)
    await flushPromises()
    await h.router.push('/courses/joined')
    await flushPromises()
    refreshed.resolve([course])
    await flushPromises()
    expect(h.wrapper.find('.is-new').exists()).toBe(false)
    expect(h.wrapper.find('[data-test="course-join-success"]').exists()).toBe(false)
  })
  it('切课取消邀请码读取，旧课程晚到的码不会覆盖新课程', async () => {
    const pending = deferred<InviteCodeResponse>()
    const api = fakeInvite({ get: (cid) => cid === 'c1' ? pending.promise : Promise.resolve(nextInvite) })
    const h = await mountInvite({ role: 'teacher', inviteApi: api })
    expect(api.get).toHaveBeenCalledTimes(1)
    const signal = api.get.mock.calls[0]![1]!.signal!
    await h.router.push('/courses/c2/members')
    await flushPromises()
    expect(signal.aborted).toBe(true)
    pending.resolve(invite)
    await flushPromises()
    expect(h.wrapper.get('[data-test="invite-code-value"]').text()).toBe(nextInvite.code)
  })
  it('重置需要确认并同步防重入，处理中禁用复制与取消', async () => {
    const pending = deferred<InviteCodeResponse>()
    const h = await mountInvite({ role: 'teacher', inviteApi: fakeInvite({ rotate: () => pending.promise }) })
    await h.wrapper.get('[data-test="invite-code-reset"]').trigger('click')
    const confirm = h.wrapper.get('[data-test="invite-code-reset-confirm"]').element
    confirm.dispatchEvent(new MouseEvent('click', { bubbles: true }))
    confirm.dispatchEvent(new MouseEvent('click', { bubbles: true }))
    await flushPromises()
    expect(h.api.rotate).toHaveBeenCalledTimes(1)
    expect(h.wrapper.get('[data-test="invite-code-copy"]').attributes('disabled')).toBeDefined()
    expect(h.wrapper.get('[data-test="invite-code-reset-cancel"]').attributes('disabled')).toBeDefined()
    pending.resolve(nextInvite)
    await flushPromises()
    expect(h.wrapper.get('[data-test="invite-code-value"]').text()).toBe(nextInvite.code)
  })
  it('换号取消重置，旧重置结果不会覆盖当前账号读取的码', async () => {
    const pending = deferred<InviteCodeResponse>()
    const h = await mountInvite({ role: 'teacher', inviteApi: fakeInvite({ rotate: () => pending.promise }) })
    await h.wrapper.get('[data-test="invite-code-reset"]').trigger('click')
    await h.wrapper.get('[data-test="invite-code-reset-confirm"]').trigger('click')
    const signal = h.api.rotate.mock.calls[0]![1]!.signal!
    h.api.get.mockResolvedValue(nextInvite)
    h.signIn('session-two')
    await flushPromises()
    expect(signal.aborted).toBe(true)
    pending.resolve({ ...invite, code: 'DEF456' })
    await flushPromises()
    expect(h.wrapper.get('[data-test="invite-code-value"]').text()).toBe(nextInvite.code)
    expect(h.wrapper.find('[data-test="invite-code-status"]').exists()).toBe(false)
  })
  it('换号后旧剪贴板结果不显示为新邀请码的复制成功', async () => {
    const pending = deferred<void>()
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => pending.promise } })
    const h = await mountInvite({ role: 'teacher' })
    await h.wrapper.get('[data-test="invite-code-copy"]').trigger('click')
    h.signIn('session-two')
    await flushPromises()
    pending.resolve()
    await flushPromises()
    expect(h.wrapper.find('[data-test="invite-code-copy-status"]').exists()).toBe(false)
  })
  it('离开成员页取消邀请码读取并忽略迟到结果', async () => {
    const pending = deferred<InviteCodeResponse>()
    const h = await mountInvite({ role: 'teacher', inviteApi: fakeInvite({ get: () => pending.promise }) })
    const signal = h.api.get.mock.calls[0]![1]!.signal!
    await h.router.push('/teacher')
    await flushPromises()
    expect(signal.aborted).toBe(true)
    pending.resolve(invite)
    await flushPromises()
    expect(h.wrapper.find('[data-test="invite-code-panel"]').exists()).toBe(false)
    expect(h.wrapper.text()).not.toContain(invite.code)
  })
})
